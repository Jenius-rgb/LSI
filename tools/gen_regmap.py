#!/usr/bin/env python3
"""Generate the Verilog header and Python constants from spec/regmap.yaml."""
from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "regmap.yaml"
VERILOG_OUT = ROOT / "rtl" / "gen" / "sentinel_regmap.vh"
PYTHON_OUT = ROOT / "sw" / "sentinel" / "regmap.py"

HEADER = "GENERATED by tools/gen_regmap.py from spec/regmap.yaml. Do not edit."


def _fields(reg: dict) -> list[tuple[str, int, int]]:
    out = []
    for f in reg.get("fields", []):
        lsb = f["bit"] if "bit" in f else f["lsb"]
        out.append((f["name"], lsb, f.get("width", 1)))
    return out


def load() -> dict:
    with open(SPEC, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def render_verilog(rm: dict) -> str:
    lines = [f"// {HEADER}", "`ifndef SENTINEL_REGMAP_VH", "`define SENTINEL_REGMAP_VH", ""]
    lines.append(f"`define SNT_VER_MAJOR {rm['version']['major']}")
    lines.append(f"`define SNT_VER_MINOR {rm['version']['minor']}")
    lines.append("")
    for name, m in rm["memory"].items():
        lines.append(f"`define SNT_MEM_{name}_BASE 24'h{m['base']:06X}")
    lines.append("")
    lines.append(f"`define SNT_CNT_BASE 12'h{rm['counters']['base']:03X}")
    lines.append("")
    for reg in rm["registers"]:
        lines.append(f"`define SNT_REG_{reg['name']} 12'h{reg['offset']:03X}")
        for fname, lsb, width in _fields(reg):
            lines.append(f"`define SNT_{reg['name']}_{fname}_LSB {lsb}")
            lines.append(f"`define SNT_{reg['name']}_{fname}_W {width}")
    lines += ["", "`endif", ""]
    return "\n".join(lines)


def render_python(rm: dict) -> str:
    lines = [f'"""{HEADER}"""', ""]
    lines.append(f"VERSION_MAJOR = {rm['version']['major']}")
    lines.append(f"VERSION_MINOR = {rm['version']['minor']}")
    lines.append(f"LAYER_TABLE_INDEX = {rm['layer_table_index']}")
    lines.append(f"COUNTER_BASE = 0x{rm['counters']['base']:03X}")
    lines.append(f"COUNTER_LAYERS = {rm['counters']['per_layer']['layers']}")
    lines.append(f"COUNTER_STRIDE = {rm['counters']['per_layer']['stride']}")
    lines.append(f"COUNTER_TYPES = {rm['counters']['per_layer']['types']!r}")
    lines.append(f"LANE_CORRECTION_BASE = {rm['counters']['lane_correction_base']}")
    lines.append(f"LOG_OVERFLOW_INDEX = {rm['counters']['log_overflow_index']}")
    lines.append("")
    for name, m in rm["memory"].items():
        lines.append(f"MEM_{name}_BASE = 0x{m['base']:06X}")
        lines.append(f"MEM_{name}_SIZE = 0x{m['size']:X}")
    lines.append("")
    for reg in rm["registers"]:
        lines.append(f"REG_{reg['name']} = 0x{reg['offset']:03X}")
        for fname, lsb, width in _fields(reg):
            lines.append(f"{reg['name']}_{fname}_LSB = {lsb}")
            lines.append(f"{reg['name']}_{fname}_WIDTH = {width}")
    lines.append("")
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    rm = load()
    return {VERILOG_OUT: render_verilog(rm), PYTHON_OUT: render_python(rm)}


def main() -> int:
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
